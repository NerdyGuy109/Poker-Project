#!/usr/bin/env node
/*
 * Builds js/drawcharts.js: odds for every 2-7 starting draw (keeping 2, 3 or 4 different cards
 * from deuce to ten). Single draw is exact; triple draw is simulated with a fixed seed.
 *
 *   node tools/build-draw-charts.js [trials]
 */
'use strict';
const fs = require('fs');
const path = require('path');
const L = require('../js/lowball.js');

const TRIALS = +(process.argv[2] || 20000);

const rng = L.seededRandom(27); // reproducible chart

const RANKS = [0, 1, 2, 3, 4, 5, 6, 7, 8]; // deuce .. ten
function subsets(k, start, acc, out) {
  if (acc.length === k) { out.push(acc.slice()); return out; }
  for (let i = start; i < RANKS.length; i++) {
    acc.push(RANKS[i]);
    subsets(k, i + 1, acc, out);
    acc.pop();
  }
  return out;
}

const round = (x) => Math.round(x * 10000) / 10000;
const entries = [];
const started = Date.now();
for (const k of [4, 3, 2]) {
  for (const ranks of subsets(k, 0, [], [])) {
    const kept = L.sampleCards(ranks.slice().reverse());
    const keptSet = new Set(kept);
    const deck = [];
    for (let c = 0; c < 52; c++) if (!keptSet.has(c)) deck.push(c);
    const single = L.singleDrawOdds(kept, deck);
    const triple = {};
    for (const t of L.TARGETS) triple[t.id] = L.multiDrawOdds(kept, deck, 3, t.rank, TRIALS, rng);
    entries.push({
      keep: ranks.slice().reverse().map(L.rankText).join('-'),
      draw: 5 - k,
      single: Object.fromEntries(Object.entries(single).map(([id, p]) => [id, round(p)])),
      triple: Object.fromEntries(Object.entries(triple).map(([id, p]) => [id, round(p)])),
    });
  }
  process.stderr.write('kept ' + k + ' cards done (' + Math.round((Date.now() - started) / 1000) + 's)\n');
}

const data = { trials: TRIALS, entries };
const out = '// Generated by tools/build-draw-charts.js; do not edit by hand.\n' +
  '// Odds of finishing with each 2-7 low or better from every starting draw.\n' +
  '(function (root) {\n  var data = ' + JSON.stringify(data) + ';\n' +
  '  if (typeof module !== \'undefined\' && module.exports) module.exports = data;\n' +
  '  else root.DrawCharts = data;\n' +
  '})(typeof self !== \'undefined\' ? self : this);\n';
fs.writeFileSync(path.join(__dirname, '..', 'js', 'drawcharts.js'), out);
process.stderr.write('wrote ' + entries.length + ' entries\n');
