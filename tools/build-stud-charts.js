#!/usr/bin/env node
/*
 * Builds js/studcharts.js: exact odds by seventh street for stud starting hands.
 * Razz and stud 8: every unpaired three-card start from ace to ten (mixed suits).
 * Stud: one representative hand for each kind of start. No dead cards are assumed.
 *
 *   node tools/build-stud-charts.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const P = require('../js/poker.js');
const S = require('../js/stud.js');

const round = (x) => Math.round(x * 100000) / 100000;
const LOW = 'A23456789T';
// Ace-low rank index (0 = ace) to a card of that rank in suit s.
const cardOf = (lowIdx, s) => (((lowIdx + 12) % 13) << 2) | s;

const started = Date.now();
const lowStarts = [];
for (let a = 0; a < 10; a++) {
  for (let b = a + 1; b < 10; b++) {
    for (let c = b + 1; c < 10; c++) {
      const cards = [cardOf(c, 0), cardOf(b, 1), cardOf(a, 2)];
      const razz = S.analyzeHand(cards, [], 'razz');
      const stud8 = S.analyzeHand(cards, [], 'stud8');
      lowStarts.push({
        start: [c, b, a].map((i) => (LOW[i] === 'T' ? '10' : LOW[i])).join('-'),
        razz: Object.fromEntries(['5', '6', '7', '8', '9', '10'].map((k) => [k, round(razz.low[k])])),
        stud8: {
          low8: round(stud8.low['8']), low7: round(stud8.low['7']), low6: round(stud8.low['6']),
          twoPair: round(stud8.high[2]), straight: round(stud8.high[4]),
        },
      });
    }
  }
}
process.stderr.write('low starts done (' + Math.round((Date.now() - started) / 1000) + 's)\n');

const STUD_STARTS = [
  ['Rolled-up trips', '7s 7d 7c'],
  ['Big pair (buried)', 'Ks Kd 4c'],
  ['Small pair (buried)', '5s 5d Kc'],
  ['Three to a straight flush', '9h 8h 7h'],
  ['Three to a straight flush, one gap', 'Jh Th 8h'],
  ['Three to a flush', 'Kh 9h 4h'],
  ['Three to a straight', '9s 8d 7c'],
  ['Three to a straight, one gap', '9s 8d 6c'],
  ['High cards, no pair or draw', 'As Kd 7c'],
];
const studStarts = STUD_STARTS.map(([kind, hand]) => {
  const a = S.analyzeHand(P.parseCards(hand), [], 'stud');
  return { kind, hand, high: a.high.map(round) };
});

const data = { lowStarts, studStarts };
const out = '// Generated by tools/build-stud-charts.js; do not edit by hand.\n' +
  '// Exact odds by seventh street for stud, stud 8 and razz starting hands (no dead cards).\n' +
  '(function (root) {\n  var data = ' + JSON.stringify(data) + ';\n' +
  '  if (typeof module !== \'undefined\' && module.exports) module.exports = data;\n' +
  '  else root.StudCharts = data;\n' +
  '})(typeof self !== \'undefined\' ? self : this);\n';
fs.writeFileSync(path.join(__dirname, '..', 'js', 'studcharts.js'), out);
process.stderr.write('wrote ' + lowStarts.length + ' low starts and ' + studStarts.length + ' stud starts\n');
